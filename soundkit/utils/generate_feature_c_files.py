from pathlib import Path
import numpy as np
from soundkit.utils.converter_fix_point import int2str_array
def generate_feature_c_files(
    file_name: str,
    param_struct_name: str,
    dir: str,
    feature_mean: np.ndarray | None,
    feature_std: np.ndarray | None,
    *,
    sampling_rate: int = 16000,
    fftsize: int = 512,
    winsize_stft: int = 480,
    hopsize_stft: int = 160,
    num_mfltrBank: int = 69,
    num_dnsmpl: int = 1,
    start_bin: int = 0,
    is_dcrm: int = 1,
    pre_gain_q1: float = 8.0,
    lookahead: int = 1,
    stft_win_coeff_name: str = "stft_win_coeff_w480_h160",
    filterbank_name: str | None = "filter_banks",
    feature_type: str = "mel",
    num_frames_infer: int = 1,
    task: str = "se",
):
    if num_mfltrBank < 0:
        feature_extraction=0
        feature_qbits=15
    else:
        feature_extraction=1
        feature_qbits=15

    if filterbank_name is None:
        filter_name_def='\n'
        filterbank_name = '(const int16_t*)(void*)0'

    else:
        filter_name_def = f"extern const int16_t {filterbank_name}[];"
        if feature_type == "erb_complex" or feature_type == "erb_mag":
            invfilter_name_def = f"extern const int16_t {filterbank_name}_inv[];"
    if feature_type == "mel":
        feature_type_c="feat_mel"
    elif feature_type == "erb_complex":
        feature_type_c="feat_spec_erb"
    elif feature_type == "erb_mag":
        feature_type_c="feat_erb_mag"
    elif feature_type == "logpspec":
        feature_type_c="feat_logpspec"
    elif feature_type == "hybrid":
        feature_type_c="feat_hybrid"
    elif feature_type == "time":
        feature_type_c="feat_time"
    else:
        raise ValueError(
            f"Unsupported feature type for C generation:" ,
            f" {feature_type}")
    # === Generate .c file

    c_code = f"""// auto-generated by generate_nn_c_files
// arm_core = cortex-M55
#include <stdint.h>
#include <stddef.h>
#include "neural_nets.h"
#include "activation.h"
#include "affine.h"
#include "lstm.h"
#include "nn_speech.h"
#include "{file_name}.h"

extern const int16_t {stft_win_coeff_name}[];

{filter_name_def}
{invfilter_name_def if feature_type == "erb_complex" else ""}

PARAMS_NNSP {param_struct_name} = {{
    .samplingRate = {sampling_rate},
    .fftsize = {fftsize},
    .winsize_stft = {winsize_stft},
    .hopsize_stft = {hopsize_stft},
    .num_mfltrBank = {num_mfltrBank},
    .num_dnsmpl = {num_dnsmpl},
    .pt_stft_win_coeff = {stft_win_coeff_name},
    .p_melBanks = {filterbank_name},
    .start_bin = {start_bin},
    .is_dcrm = {is_dcrm},
    .pre_gain_q1 = {int(pre_gain_q1 * 2)}, // q1
    .feature_type = {feature_type_c},
}};


/*************stats***********/
{int2str_array(f"feature_mean_{task}", feature_mean*32768, nbits=32) if feature_mean is not None else f"const int32_t *feature_mean_{task} = NULL;"}

{int2str_array(f"feature_stdR_{task}", feature_std*32768, nbits=32) if feature_std is not None else f"const int32_t *feature_stdR_{task} = NULL;"}
"""
    Path(f"{dir}/{file_name}.c").write_text(c_code)
    print(f"✅ Wrote {file_name}.c")

    # === Generate .h file
    h_code = f"""#ifndef __DEF_NN3_{task.upper()}__
#define __DEF_NN3_{task.upper()}__

#include <stdint.h>
#include "neural_nets.h"
#include "nn_speech.h"

{f"extern const int32_t *feature_mean_{task};" if feature_mean is None else f"extern const int32_t feature_mean_{task}[];"}
{f"extern const int32_t *feature_stdR_{task};" if feature_std is None else f"extern const int32_t feature_stdR_{task}[];"}

#define NUM_LOOKAHEAD {lookahead}
#define FEATURE_EXTRACTION {feature_extraction}
#define FEATURE_QBIT {feature_qbits}
#define NUM_FRAMES_INFER {num_frames_infer}
extern PARAMS_NNSP {param_struct_name};

#endif  // __DEF_NN3_SE__
"""
    Path(f"{dir}/{file_name}.h").write_text(h_code)
    print(f"✅ Wrote {file_name}.h")
